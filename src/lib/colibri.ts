/** Bounding box of the figure, for fitting it into an SVG viewBox. */
export const COLIBRI_BOUNDS = (() => {
  const xs = COLIBRI_POINTS.map(([x]) => x);
  const ys = COLIBRI_POINTS.map(([, y]) => y);
  return {
    minX: Math.min(...xs),
    maxX: Math.max(...xs),
    minY: Math.min(...ys),
    maxY: Math.max(...ys),
  };
})();

/** Closed SVG path through the points, y flipped for SVG's downward axis. */
export function colibriPath(): string {
  const [first, ...rest] = COLIBRI_POINTS;
  const p = ([x, y]: Point) => `${x} ${-y}`;
  return `M${p(first)} ${rest.map((pt) => `L${p(pt)}`).join(" ")} Z`;
}

/** viewBox that frames the figure with `pad` units on every side. */
export function colibriViewBox(pad = 4): string {
  const { minX, maxX, minY, maxY } = COLIBRI_BOUNDS;
  return `${minX - pad} ${-maxY - pad} ${maxX - minX + pad * 2} ${maxY - minY + pad * 2}`;
}

