import { readFile } from "fs/promises";
import { join } from "path";
import fontkit from "@pdf-lib/fontkit";
import {
  PDFDocument,
  rgb,
  type PDFFont,
  type PDFPage,
  type RGB,
} from "pdf-lib";
import layout from "./certificateLayout.json";

// The three certificates GDG ICA issues. Each has its own static template
// (title, seal) and its own certifying paragraph below.
export const CERTIFICATE_KINDS = ["attendee", "volunteer", "speaker"] as const;
export type CertificateKind = (typeof CERTIFICATE_KINDS)[number];

// Static templates (frame, colibrí, GDG lockup, title, signature, seal),
// one per kind, generated by scripts/certificates/build-templates.mjs.
// They MUST NOT contain the recipient name or the paragraph: those are
// drawn here, inside the band the generator leaves empty. Both sides read
// certificateLayout.json, whose y values are measured from the TOP of the
// page (SVG convention); pdf-lib measures from the bottom, hence toPdfY.
const ASSETS = join(__dirname, "..", "..", "assets");
// A fixed file per kind, never a path built from the input: `kind` is
// validated upstream, but the path must not depend on that.
function templatePath(kind: CertificateKind): string {
  switch (kind) {
    case "attendee":
      return join(ASSETS, "certificates", "attendee.pdf");
    case "volunteer":
      return join(ASSETS, "certificates", "volunteer.pdf");
    case "speaker":
      return join(ASSETS, "certificates", "speaker.pdf");
    default:
      throw new Error(`Unknown certificate kind: ${String(kind)}`);
  }
}
const FONT_PATH = (file: string) => join(ASSETS, "fonts", file);

const FONTS = {
  name: "BodoniModa-MediumItalic.ttf",
  regular: "Geist-Regular.ttf",
  bold: "Geist-Medium.ttf",
} as const;

const MONTHS_ES = [
  "enero",
  "febrero",
  "marzo",
  "abril",
  "mayo",
  "junio",
  "julio",
  "agosto",
  "septiembre",
  "octubre",
  "noviembre",
  "diciembre",
];

export interface CertificateInput {
  kind: CertificateKind;
  recipientName: string;
  eventName: string;
  startTime: string;
  endTime: string;
  hours: number;
  /** ISO date `YYYY-MM-DD` of the event. */
  eventDate: string;
  /** Defaults to "GDG ICA". */
  organizer?: string;
}

function hexToRgb(hex: string): RGB {
  const n = parseInt(hex.replace("#", ""), 16);
  return rgb(((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255);
}

const COLORS = {
  name: hexToRgb(layout.colors.gold),
  text: hexToRgb(layout.colors.ivoryDim),
  emphasis: hexToRgb(layout.colors.ivory),
};

const toPdfY = (topY: number) => layout.page.height - topY;

/** "2026-04-18" -> "18 de abril de 2026". Falls back to the raw string. */
export function formatSpanishDate(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!m) return iso;
  const year = Number(m[1]);
  const month = Number(m[2]) - 1;
  const day = Number(m[3]);
  if (month < 0 || month > 11) return iso;
  return `${day} de ${MONTHS_ES[month]} de ${year}`;
}

/** 1 -> "1 hora", 4 -> "4 horas", 2.5 -> "2,5 horas". */
export function formatHours(hours: number): string {
  const n = Number.isInteger(hours)
    ? String(hours)
    : String(Math.round(hours * 100) / 100).replace(".", ",");
  return `${n} ${hours === 1 ? "hora" : "horas"}`;
}

// Normalize characters text pasted from docs tends to carry, then drop
// anything the embedded font has no glyph for, so a stray emoji in a name
// or event title prints as nothing instead of as a .notdef box.
function sanitize(text: string, supported: Set<number>): string {
  const normalized = text
    .normalize("NFC")
    .replace(/[\u00A0\u2007\u202F]/g, " ")
    .replace(/\s+/g, " ");
  let out = "";
  for (const ch of normalized) {
    const code = ch.codePointAt(0) ?? 0;
    if (code === 32 || supported.has(code)) out += ch;
  }
  return out.replace(/\s+/g, " ").trim();
}

// "6:00 p.m." must never wrap between the number and "p.m.", nor the date
// after its day number: inner spaces become NBSP, which layoutRuns does
// not split on and prints as a plain space.
const NBSP = "\u00A0";
const keepTogether = (s: string) => s.replace(/ /g, NBSP);
const display = (s: string) => s.replace(/\u00A0/g, " ");

interface Run {
  text: string;
  bold: boolean;
}

/**
 * The certifying paragraph for each kind. It follows "Se otorga a
 * <nombre>" printed by the template, so it opens with "Por …". Only what
 * the recipient will look for is emphasised (event, date, hours); the
 * organiser and the times stay in the running text, so the paragraph
 * reads as a sentence and not as a filled-in form.
 */
export function paragraphRuns(
  kind: CertificateKind,
  v: {
    eventName: string;
    organizer: string;
    date: string;
    startTime: string;
    endTime: string;
    hours: string;
  }
): Run[] {
  const when: Run[] = [
    { text: ", organizado por ", bold: false },
    { text: v.organizer, bold: false },
    { text: " el ", bold: false },
    { text: keepTogether(v.date), bold: true },
    { text: ", de ", bold: false },
    {
      text: `${keepTogether(v.startTime)} a ${keepTogether(v.endTime)}`,
      bold: false,
    },
  ];
  switch (kind) {
    case "volunteer":
      return [
        {
          text: "Por su compromiso como parte del equipo de voluntariado de ",
          bold: false,
        },
        { text: v.eventName, bold: true },
        ...when,
        { text: ", aportando ", bold: false },
        { text: v.hours, bold: true },
        { text: " de trabajo a la comunidad.", bold: false },
      ];
    case "speaker":
      return [
        {
          text: "Por compartir su conocimiento como speaker en ",
          bold: false,
        },
        { text: v.eventName, bold: true },
        ...when,
        {
          text: ", contribuyendo al crecimiento de la comunidad de desarrolladores.",
          bold: false,
        },
      ];
    case "attendee":
    default:
      return [
        { text: "Por su participación como asistente en ", bold: false },
        { text: v.eventName, bold: true },
        ...when,
        { text: ", completando ", bold: false },
        { text: v.hours, bold: true },
        { text: " de desarrollo profesional.", bold: false },
      ];
  }
}

interface Token {
  text: string;
  bold: boolean;
  /** No space between this token and the previous one (punctuation glued to a bold value). */
  glued: boolean;
}

// Greedy word-wrap across mixed bold/regular runs. Punctuation that opens
// a run (", organizado por") stays glued to the previous token so a comma
// never starts a line or floats one space away from the bold value.
export function layoutRuns(
  runs: Run[],
  regular: PDFFont,
  bold: PDFFont,
  size: number,
  maxWidth: number
): Token[][] {
  const tokens: Token[] = [];
  // A run boundary is a word break only when one side carries the space:
  // "… el " + "18 de abril" breaks, "GDG ICA" + ", de " does not.
  let prevEndsWithSpace = true;
  for (const run of runs) {
    if (!run.text) continue;
    const startsWithSpace = /^[ \t\r\n]/.test(run.text);
    const parts = run.text.split(/[ \t\r\n]+/).filter(Boolean);
    parts.forEach((p, idx) => {
      tokens.push({
        text: p,
        bold: run.bold,
        glued:
          idx === 0 &&
          tokens.length > 0 &&
          !startsWithSpace &&
          !prevEndsWithSpace,
      });
    });
    prevEndsWithSpace = /[ \t\r\n]$/.test(run.text);
  }

  const widthOf = (t: Token) =>
    (t.bold ? bold : regular).widthOfTextAtSize(display(t.text), size);
  const spaceW = regular.widthOfTextAtSize(" ", size);

  const lines: Token[][] = [];
  let line: Token[] = [];
  let lineW = 0;
  for (const tok of tokens) {
    const w = widthOf(tok);
    const add = line.length === 0 ? w : (tok.glued ? 0 : spaceW) + w;
    if (line.length > 0 && !tok.glued && lineW + add > maxWidth) {
      lines.push(line);
      line = [{ ...tok, glued: false }];
      lineW = w;
    } else {
      line.push(tok);
      lineW += add;
    }
  }
  if (line.length > 0) lines.push(line);
  return lines;
}

/**
 * Largest size (in 0.5pt steps, capped at `max`) at which `text` fits
 * `maxWidth`. Width scales linearly with size, kerning included, so this
 * is exact rather than a search; the caller decides what a size below its
 * minimum means.
 */
function fitSize(
  font: PDFFont,
  text: string,
  max: number,
  maxWidth: number
): number {
  const perPoint = font.widthOfTextAtSize(text, 1);
  if (perPoint <= 0) return max;
  return Math.min(max, Math.floor((maxWidth / perPoint) * 2) / 2);
}

// Names are capped well below this by the schemas; the guard keeps the
// loop below bounded whatever reaches it.
const MAX_NAME_CHARS = 400;

/** Splits at the space closest to the middle, for two-line names. */
function splitInTwo(text: string): [string, string] | null {
  if (typeof text !== "string" || text.length > MAX_NAME_CHARS) return null;
  const mid = text.length / 2;
  let best = -1;
  for (let i = 0; i < text.length; i++) {
    if (
      text[i] === " " &&
      (best < 0 || Math.abs(i - mid) < Math.abs(best - mid))
    ) {
      best = i;
    }
  }
  if (best < 0) return null;
  return [text.slice(0, best), text.slice(best + 1)];
}

export interface NameLayout {
  size: number;
  lines: { text: string; baselineY: number }[];
}

/**
 * One line at up to `maxSize`, shrinking to `minSize`; past that, two
 * lines; a name that still does not fit (one 120-char word) keeps
 * shrinking until it does.
 */
export function layoutName(font: PDFFont, name: string): NameLayout {
  const n = layout.name;
  const width = layout.column.width;
  const single = fitSize(font, name, n.maxSize, width);
  const halves = single < n.minSize ? splitInTwo(name) : null;
  if (!halves) {
    return { size: single, lines: [{ text: name, baselineY: n.baselineY }] };
  }
  const size = Math.min(
    ...halves.map((h) => fitSize(font, h, n.twoLineMaxSize, width))
  );
  return {
    size,
    lines: halves.map((text, i) => ({
      text,
      baselineY: n.twoLineBaselinesY[i],
    })),
  };
}

function drawParagraph(
  page: PDFPage,
  lines: Token[][],
  size: number,
  regular: PDFFont,
  bold: PDFFont
) {
  const p = layout.paragraph;
  const lineHeight = size * p.lineHeightRatio;
  const spaceW = regular.widthOfTextAtSize(" ", size);
  lines.forEach((line, i) => {
    let x = layout.column.x;
    const y = toPdfY(p.firstBaselineY + i * lineHeight);
    line.forEach((tok, j) => {
      const font = tok.bold ? bold : regular;
      if (j > 0 && !tok.glued) x += spaceW;
      const text = display(tok.text);
      page.drawText(text, {
        x,
        y,
        size,
        font,
        color: tok.bold ? COLORS.emphasis : COLORS.text,
      });
      x += font.widthOfTextAtSize(text, size);
    });
  });
}

// Templates and fonts are read once per instance and reused across the
// recipients of a batch (and across warm invocations).
const fileCache = new Map<string, Promise<Buffer>>();
function cachedRead(path: string): Promise<Buffer> {
  let p = fileCache.get(path);
  if (!p) {
    p = readFile(path);
    p.catch(() => fileCache.delete(path));
    fileCache.set(path, p);
  }
  return p;
}

/**
 * Generates the certificate PDF in memory from the bundled template of
 * its kind. Nothing is persisted — the caller attaches the returned bytes
 * to an email and discards them.
 */
export async function buildCertificatePdf(
  input: CertificateInput
): Promise<Uint8Array> {
  const [templateBytes, nameBytes, regularBytes, boldBytes] = await Promise.all(
    [
      cachedRead(templatePath(input.kind)),
      cachedRead(FONT_PATH(FONTS.name)),
      cachedRead(FONT_PATH(FONTS.regular)),
      cachedRead(FONT_PATH(FONTS.bold)),
    ]
  );
  const doc = await PDFDocument.load(templateBytes);
  doc.registerFontkit(fontkit);
  const [nameFont, regular, bold] = await Promise.all([
    doc.embedFont(nameBytes, { subset: true }),
    doc.embedFont(regularBytes, { subset: true }),
    doc.embedFont(boldBytes, { subset: true }),
  ]);
  const page = doc.getPages()[0];

  const nameSet = new Set(nameFont.getCharacterSet());
  const textSet = new Set(
    regular.getCharacterSet().filter((c) => bold.getCharacterSet().includes(c))
  );
  const clean = (s: string) => sanitize(s, textSet);

  const name = sanitize(input.recipientName, nameSet);
  const nameLayout = layoutName(nameFont, name);
  for (const line of nameLayout.lines) {
    page.drawText(line.text, {
      x: layout.column.x,
      y: toPdfY(line.baselineY),
      size: nameLayout.size,
      font: nameFont,
      color: COLORS.name,
    });
  }

  const runs = paragraphRuns(input.kind, {
    eventName: clean(input.eventName),
    organizer: clean(input.organizer || "GDG ICA"),
    date: formatSpanishDate(input.eventDate),
    startTime: clean(input.startTime),
    endTime: clean(input.endTime),
    hours: formatHours(input.hours),
  });
  const p = layout.paragraph;
  let size = p.size;
  let lines = layoutRuns(runs, regular, bold, size, p.width);
  while (lines.length > p.maxLines && size > p.minSize) {
    size -= 0.5;
    lines = layoutRuns(runs, regular, bold, size, p.width);
  }
  drawParagraph(page, lines, size, regular, bold);

  doc.setTitle(`Certificado · ${name}`);
  doc.setAuthor("GDG ICA");
  doc.setCreator("GDG ICA");
  doc.setProducer("GDG ICA");
  return doc.save();
}
