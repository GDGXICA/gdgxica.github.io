import { z } from "zod";
import { CERTIFICATE_KINDS } from "../services/certificateKinds";

// Certificates per event and manual certificates. Sending is a queue: these
// requests only record who should receive what, and the drain in
// triggers/drainCertificateEmails.ts sends it. That is what keeps any of
// them inside Hosting's 60-second limit, whatever the number of people.

const namePart = z.string().trim().max(100);
const email = z.string().trim().toLowerCase().email().max(254);
const hhmm = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, "Hora inválida");
const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Fecha inválida");
// Roster ids are `t_<ticket>`; a ticket may already use 100 characters.
const docId = z.string().regex(/^[A-Za-z0-9_-]{1,120}$/);
const personHours = z.number().positive().max(500).nullable().optional();

export const certificateSettingsSchema = z
  .object({
    eventName: z.string().trim().min(1).max(300),
    eventDate: isoDate,
    startTime: hhmm,
    endTime: hhmm,
    // 0 is allowed: an event may only issue speaker certificates, which do
    // not credit hours. Sending a kind that needs them checks it then.
    hours: z.number().min(0).max(500),
  })
  .strict();
export type CertificateSettingsBody = z.infer<typeof certificateSettingsSchema>;

const personSchema = z
  .object({
    firstName: namePart.min(1),
    lastName: namePart,
    email,
  })
  .strict();

export const certificatePeopleCreateSchema = z
  .object({
    // Attendees come from the check-in roster; only these two are typed in.
    kind: z.enum(["volunteer", "speaker"]),
    people: z
      .array(personSchema.extend({ hours: personHours }).strict())
      .min(1)
      .max(200),
  })
  .strict();
export type CertificatePeopleCreateBody = z.infer<
  typeof certificatePeopleCreateSchema
>;

export const certificatePersonUpdateSchema = z
  .object({
    // Required the first time an attendee is edited: their certificate
    // document does not exist until then, and its id is a hash.
    rosterId: docId.optional(),
    firstName: namePart.min(1).optional(),
    lastName: namePart.optional(),
    email: email.optional(),
    hours: personHours,
    excluded: z.boolean().optional(),
  })
  .strict()
  .refine(
    (b) =>
      b.firstName !== undefined ||
      b.lastName !== undefined ||
      b.email !== undefined ||
      b.hours !== undefined ||
      b.excluded !== undefined,
    "Nada que cambiar"
  );
export type CertificatePersonUpdateBody = z.infer<
  typeof certificatePersonUpdateSchema
>;

export const certificateEnqueueSchema = z
  .object({
    kind: z.enum(CERTIFICATE_KINDS),
    // Attendees: roster document ids, re-checked for check-in on the
    // server. Volunteers and speakers: certificate document ids. Either
    // way, exactly the list the organizer confirmed in the panel.
    ids: z.array(docId).min(1).max(2000),
    // Without it, someone who already received the certificate is skipped.
    resend: z.boolean().optional(),
  })
  .strict();
export type CertificateEnqueueBody = z.infer<typeof certificateEnqueueSchema>;

export const certificateCancelSchema = z
  .object({ ids: z.array(docId).min(1).max(2000) })
  .strict();
export type CertificateCancelBody = z.infer<typeof certificateCancelSchema>;

export const certificatePreviewSchema = z
  .object({
    kind: z.enum(CERTIFICATE_KINDS),
    name: z.string().trim().min(1).max(200),
    content: certificateSettingsSchema,
    hours: personHours,
  })
  .strict();
export type CertificatePreviewBody = z.infer<typeof certificatePreviewSchema>;

export const certificateManualSchema = z
  .object({
    // Generated by the panel once per form; a retried submit reuses it, so
    // it cannot queue the same people twice.
    submissionId: z.string().uuid(),
    kind: z.enum(CERTIFICATE_KINDS),
    // The event it was picked from, for the record. The certificate prints
    // `content`, which may differ (or describe an event not in the list).
    eventSlug: z
      .string()
      .regex(/^[a-zA-Z0-9_-]{1,100}$/)
      .nullable(),
    content: certificateSettingsSchema,
    recipients: z.array(personSchema).min(1).max(100),
  })
  .strict();
export type CertificateManualBody = z.infer<typeof certificateManualSchema>;
